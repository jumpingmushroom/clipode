// Generates src/api/types.ts (GET paths and query parameters) from the instance's /api/openapi.json,
// and records the Paperclip version it came from. Response bodies are typed from @paperclipai/shared.
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript"
import { signedInClient } from "./env.ts"

const out = new URL("../src/api/types.ts", import.meta.url).pathname
const client = await signedInClient()
try {
  // The document's info.version is a fixed "1.0.0", so the real version comes from /api/health.
  const health = await client.get<{ version?: string; commit?: string }>("/api/health")
  const doc = await client.get<OpenAPI3>("/api/openapi.json")
  // Phase 1 only reads, and response shapes come from @paperclipai/shared, so keep GET operations only.
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    if (!item || !("get" in item)) delete doc.paths![path]
    else doc.paths![path] = { get: item.get, parameters: item.parameters }
  }
  const ast = await openapiTS(doc)
  const header = [
    "// Generated by script/gen-types.ts. Do not edit; run `bun run gen-types` against a tested instance.",
    `// Paperclip version: ${health.version ?? "unknown"}, commit ${health.commit ?? "unknown"}.`,
    "",
  ].join("\n")
  await Bun.write(out, header + astToString(ast))
  const paths = Object.keys((doc.paths ?? {}) as object).length
  console.log(`wrote ${out}: ${paths} paths from Paperclip ${health.version ?? "unknown"}`)
} finally {
  // The cached session stays valid for the next script.
}
